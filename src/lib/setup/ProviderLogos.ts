function markFor(provider: ProviderId, model?: string): Mark {
  if (model) {
    const own = MODEL_MARKS[`${provider}/${model}`];
    if (own) return own;
  }
  return MARKS[provider] ?? MARKS.local;
}

export function getProviderPlate(provider: ProviderId, model?: string): 'bleed' | 'none' {
  return markFor(provider, model).plate;
}

/**
 * Brand mark as inline SVG.
 *
 * A monochrome mark returns both cuts, with CSS picking one by theme — doing
 * it here instead would need the theme threaded through every call site.
 */
export function getProviderLogo(provider: ProviderId, model?: string): string {
  const mark = markFor(provider, model);
  const fill = mark.fill ? ` fill="${mark.fill}"` : '';
  const svg = (body: string, cls: string) =>
    `<svg class="${cls}" viewBox="${mark.viewBox}"${fill} xmlns="http://www.w3.org/2000/svg" aria-hidden="true">${body}</svg>`;

  if (!mark.bodyDark) return svg(mark.body, 'mark');
  return svg(mark.body, 'mark mark-light') + svg(mark.bodyDark, 'mark mark-dark');
}
