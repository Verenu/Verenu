import { readFile } from 'node:fs/promises';

/**
 * All text `verenu triage` hands to the coding agent. The playbook lives in
 * PLAYBOOK.md beside this file so it can be edited as plain Markdown. It ships
 * inside the npm package.
 */
const playbookUrl = new URL('./PLAYBOOK.md', import.meta.url);

export const loadPlaybook = () => readFile(playbookUrl, 'utf8');

/** The one-line argument the agent session is launched with. */
export const buildTriageLaunchPrompt = promptFilePath =>
  `Read the file "${promptFilePath}" and follow its instructions exactly: it is your Verenu triage playbook. It starts by reading the context file, then asks the user what went wrong.`;

/** The full seed prompt, written to `prompt.md` in the triage scratch directory. */
export const buildTriageSeedPrompt = (contextFilePath, playbook) => `A Verenu user is \
having a problem with their install and started this session with \`verenu triage\`.

Machine facts (CLI version, OS, data paths, and read-only check results) are in the triage context file:

    ${contextFilePath}

Follow the playbook below. Read the context file first, then ask the user what went wrong.

---

${playbook}`;

/** Machine facts for one triage run, pre-formatted so the template stays plain. */
export const buildTriageContext = input => `# Verenu triage context

Generated by \`verenu triage\` at ${input.generatedAt}.

- CLI version: ${input.version}
- OS: ${input.os}
- Session: ${input.session}
- Node: ${input.nodeVersion}
- Launched as: ${input.launchedAs}
- Repo: https://github.com/Verenu/Verenu
${input.app
  ? `- Verenu app version: ${input.app.version} (${input.app.build} build, ${input.app.os} ${input.app.arch}), from the newest session log ${input.app.sessionLog}`
  : '- Verenu app version: not found in the session logs. Ask the user.'}
- Release tag for this version: ${input.releaseTag ?? 'unknown'}. If the tag does not exist, clone master and say that file and line references are approximate.
- Source cache directory (the playbook's source step clones the repository here): ${input.sourceCacheDir}

## Paths

- Data directory: ${input.paths.dataDir}
- Settings: ${input.paths.settingsPath}
- Database (SQLite; read-only queries only unless the user gives permission to write): ${input.paths.dbPath}
- Logs directory (session-*.log): ${input.paths.logsDir}
- Agent session file: ${input.paths.agentSessionPath}
- Models directory: ${input.paths.modelsDir}
- Backups folder (the agent creates a timestamped folder here only before changing a file, with the user's approval): ${input.paths.backupsDir}
- Secure storage service name: com.verenu.app (never read stored values)

## Read-only check results

These results come from read-only checks run when triage started. Treat them as leads.

${input.checks.map(check => `- ${check.status.toUpperCase()} ${check.name}: ${check.message}`).join('\n')}
`;
